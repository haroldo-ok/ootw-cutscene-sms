#!/usr/bin/env python3
"""awstitch.py - assemble the 4 MiB OOTW SMS ROM.

Layout: banks 0-1 = code (from code.sms); bank 2+ = data:
  tiles.bin (compact shared tile dictionary)
  tile_off.bin (u24 per entry: ROM-absolute offsets, baked here)
  15 x <scene>.awv (video streams)
  15 x <scene>.awa (PSG audio streams)

Writes rom/src/fmv_data.h with the ROM offsets. --header-only skips the ROM.
"""
import os, sys, struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
FMV = os.path.join(ROOT, 'build', 'fmv')
ROMDIR = os.path.join(ROOT, 'rom')

BANK = 16384
CODE_BANKS = 2
DATA_BASE = CODE_BANKS * BANK

SCENES = ['titles', 'intro', 'open16002', 'mut16002', 'open16003', 'cistern16003',
          'escape16003', 'open16004', 'exit16004', 'open16005', 'exit16005',
          'open16006', 'gate16006', 'ending', 'password']


def layout():
    tiles = open(os.path.join(FMV, 'tiles.bin'), 'rb').read()
    toff = open(os.path.join(FMV, 'tile_off.bin'), 'rb').read()
    awv = [open(os.path.join(FMV, s + '.awv'), 'rb').read() for s in SCENES]
    awa = [open(os.path.join(FMV, s + '.awa'), 'rb').read() for s in SCENES]

    pos = DATA_BASE
    tiles_rom = pos
    pos += len(tiles)
    if pos & 1:
        pos += 1
    toff_rom = pos
    pos += len(toff)
    if pos & 1:
        pos += 1
    awv_rom = []
    for b in awv:
        awv_rom.append(pos)
        pos += len(b)
        if pos & 1:
            pos += 1
    awa_rom = []
    for b in awa:
        awa_rom.append(pos)
        pos += len(b)
        if pos & 1:
            pos += 1

    # bake absolute tile offsets
    n = len(toff) // 3
    toff_b = bytearray()
    for i in range(n):
        o = toff[3 * i] | (toff[3 * i + 1] << 8) | (toff[3 * i + 2] << 16)
        o += tiles_rom
        toff_b += bytes([o & 255, (o >> 8) & 255, (o >> 16) & 255])

    blob = bytearray()
    base = DATA_BASE
    def put(data):
        nonlocal blob
        blob += data
        if (base + len(blob)) & 1:
            blob += b'\x00'
    put(tiles)
    put(bytes(toff_b))
    for b in awv:
        put(b)
    for b in awa:
        put(b)
    return dict(tiles_rom=tiles_rom, toff_rom=toff_rom,
                awv_rom=awv_rom, awa_rom=awa_rom, blob=bytes(blob), ntiles=n - 1)


def write_header(L):
    path = os.path.join(ROMDIR, 'src', 'fmv_data.h')
    with open(path, 'w') as f:
        f.write('/* generated by tools/awstitch.py - ROM offsets of FMV data */\n')
        f.write('#ifndef FMV_DATA_H\n#define FMV_DATA_H\n')
        f.write('#define FMV_NSCENES %d\n' % len(SCENES))
        f.write('#define ROM_TILEOFF_BASE %dUL\n' % L['toff_rom'])
        f.write('#define ROM_NTILES %d\n' % L['ntiles'])
        f.write('static const unsigned long ROM_AWV[FMV_NSCENES] = {\n')
        f.write(',\n'.join('  %dUL' % o for o in L['awv_rom']))
        f.write('\n};\n')
        f.write('static const unsigned long ROM_AWA[FMV_NSCENES] = {\n')
        f.write(',\n'.join('  %dUL' % o for o in L['awa_rom']))
        f.write('\n};\n')
        def b3(v):
            return '{ 0x%02X, 0x%02X, 0x%02X }' % (v & 0xFF, (v >> 8) & 0xFF, (v >> 16) & 0xFF)
        f.write('const unsigned char ROM_AWV_B[FMV_NSCENES][3] = {\n')
        f.write(',\n'.join('  ' + b3(o) for o in L['awv_rom']))
        f.write('\n};\n')
        f.write('const unsigned char ROM_AWA_B[FMV_NSCENES][3] = {\n')
        f.write(',\n'.join('  ' + b3(o) for o in L['awa_rom']))
        f.write('\n};\n')
        f.write('const unsigned char ROM_TILEOFF_BASE_B[3] = ' + b3(L['toff_rom']) + ';\n')
        f.write('#endif\n')
    print('wrote', path)


def build_rom(code_path, out_path, L):
    code = bytearray(open(code_path, 'rb').read())
    if len(code) < DATA_BASE:
        code += b'\x00' * (DATA_BASE - len(code))
    if len(code) > DATA_BASE:
        sys.exit('code is %d bytes, must fit in %d (2 banks)' % (len(code), DATA_BASE))
    rom = code + L['blob']
    total = len(rom)
    size = BANK
    while size < total:
        size *= 2
    if size > 4 * 1024 * 1024:
        sys.exit('ROM would be %d bytes (> 4 MiB)' % size)
    rom += b'\x00' * (size - len(rom))

    hdr = rom.find(b'TMR SEGA', 0x7ff0, 0x8000)
    if hdr < 0:
        sys.exit('SEGA header not found at 0x7ff0')
    csum = sum(rom[0:0x7ff0]) & 0xffff
    rom[hdr + 0x0a] = csum & 0xff
    rom[hdr + 0x0b] = (csum >> 8) & 0xff
    nib = {0x2000: 0x0c, 0x4000: 0x0d, 0x8000: 0x0e, 0xC000: 0x0f,
           0x10000: 0x00, 0x20000: 0x01, 0x40000: 0x02, 0x80000: 0x03,
           0x100000: 0x04, 0x200000: 0x05, 0x400000: 0x06}.get(size)
    rom[hdr + 0x0f] = (rom[hdr + 0x0f] & 0xf0) | nib
    open(out_path, 'wb').write(rom)
    print('%s: %d KB (%d banks), checksum 0x%04x' % (out_path, size // 1024, size // BANK, csum))


def main():
    L = layout()
    write_header(L)
    if '--header-only' in sys.argv:
        return
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    build_rom(args[0], args[1], L)


if __name__ == '__main__':
    main()
